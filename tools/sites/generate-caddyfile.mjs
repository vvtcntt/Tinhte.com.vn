// Sinh Caddyfile cho edge LOCAL từ Site Registry (ADR-0001 D10), mô phỏng CDN production:
//   /api/* của site có apiSurfaces → API; còn lại → app của site; alias → 308.
// Dùng: node tools/sites/generate-caddyfile.mjs [--check]   (ghi infra/local/Caddyfile; --check: báo lỗi nếu file lệch)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import { registry, resolvableSites, hostFor } from '../../frontend/packages/sites/src/index.ts';

// Upstream khi app chạy trên máy dev (docker → host). Đổi bằng biến môi trường nếu cần.
const UPSTREAMS = {
  api: process.env.TT_UPSTREAM_API ?? 'host.docker.internal:5080',
  web: process.env.TT_UPSTREAM_WEB ?? 'host.docker.internal:3000',
  cms: process.env.TT_UPSTREAM_CMS ?? 'host.docker.internal:3001',
  cdn: process.env.TT_UPSTREAM_MEDIA ?? 'host.docker.internal:9000',
};

export function generateCaddyfile(r = registry, env = 'local') {
  const e = r.environments[env];
  const port = e.publicPort ? `:${e.publicPort}` : '';
  const addr = (host) => `${e.scheme}://${host}${port}`;
  const blocks = [];
  for (const s of resolvableSites(env, r)) {
    const canonical = hostFor(s, env, s.subdomain, r);
    const upstream = UPSTREAMS[s.app];
    if (!upstream) throw new Error(`No local upstream for app "${s.app}" (site ${s.key})`);
    const api = s.apiSurfaces.length
      ? `\thandle /api/* {\n\t\treverse_proxy ${UPSTREAMS.api}\n\t}\n`
      : '';
    blocks.push(`# site: ${s.key} (${s.kind}, ${s.status})\n${addr(canonical)} {\n${api}\thandle {\n\t\treverse_proxy ${upstream}\n\t}\n}`);
    for (const alias of s.aliases) {
      blocks.push(`# alias of ${s.key}\n${addr(hostFor(s, env, alias, r))} {\n\tredir ${addr(canonical)}{uri} 308\n}`);
    }
  }
  return `# GENERATED by tools/sites/generate-caddyfile.mjs from config/sites/sites.json — DO NOT EDIT.\n{\n\tauto_https off\n}\n\n${blocks.join('\n\n')}\n`;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../infra/local/Caddyfile');
  const content = generateCaddyfile();
  if (process.argv.includes('--check')) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== content) {
      console.error('infra/local/Caddyfile is out of date — run: node tools/sites/generate-caddyfile.mjs');
      process.exit(1);
    }
    console.log('infra/local/Caddyfile is up to date');
  } else {
    writeFileSync(target, content);
    console.log(`wrote ${path.relative(process.cwd(), target)}`);
  }
}
