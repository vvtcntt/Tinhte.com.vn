// Sinh SQL đồng bộ tt.sites từ Site Registry (ADR-0001 D8). Pipeline deploy chạy sau migration.
// Site bị bỏ khỏi registry → status 'retired' (không xóa vì nội dung có thể tham chiếu).
// Dùng: node tools/sites/generate-db-sync.mjs > sites-sync.sql
import { pathToFileURL } from 'node:url';
import { registry } from '../../frontend/packages/sites/src/index.ts';

const q = (value) => `'${String(value).replace(/'/g, "''")}'`;

export function generateDbSync(r = registry) {
  const rows = r.sites.map((s) => `  (${q(s.key)}, ${q(s.label)}, ${q(s.kind)}, ${q(s.status)}, ${q(s.scope)})`).join(',\n');
  const keys = r.sites.map((s) => q(s.key)).join(', ');
  return `-- GENERATED by tools/sites/generate-db-sync.mjs from config/sites/sites.json — DO NOT EDIT.
INSERT INTO tt.sites (key, label, kind, status, scope) VALUES
${rows}
ON CONFLICT (key) DO UPDATE
  SET label = EXCLUDED.label, kind = EXCLUDED.kind, status = EXCLUDED.status, scope = EXCLUDED.scope
  WHERE (tt.sites.label, tt.sites.kind, tt.sites.status, tt.sites.scope)
        IS DISTINCT FROM (EXCLUDED.label, EXCLUDED.kind, EXCLUDED.status, EXCLUDED.scope);
UPDATE tt.sites SET status = 'retired' WHERE key NOT IN (${keys}) AND status <> 'retired';
`;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  process.stdout.write(generateDbSync());
}
