using System.Text;
using Tinhte.Platform.Sites;

namespace Tinhte.Platform.Data.Migrations;

/// <summary>
/// SQL đồng bộ <c>tt.sites</c> từ Site Registry (ADR-0001 D8), chạy sau migration (Tinhte.DbMigrator).
/// Bản C# của <c>tools/sites/generate-db-sync.mjs</c>: test <c>SiteDbSyncTests</c> so khớp từng dòng (trừ dòng tiêu đề),
/// nên sửa một bên thì phải sửa bên kia. Site bỏ khỏi registry → 'retired', không xóa.
/// </summary>
public static class SiteDbSync
{
    public const string Header = "-- GENERATED by Tinhte.Platform SiteDbSync (mirror of tools/sites/generate-db-sync.mjs) from config/sites/sites.json — DO NOT EDIT.";

    public static string Generate(IReadOnlyList<SiteDefinition> sites)
    {
        var rows = string.Join(",\n", sites.Select(s => $"  ({Q(s.Key)}, {Q(s.Label)}, {Q(s.Kind)}, {Q(s.Status)}, {Q(s.Scope)})"));
        var keys = string.Join(", ", sites.Select(s => Q(s.Key)));
        var sql = new StringBuilder();
        sql.Append(Header).Append('\n');
        sql.Append("INSERT INTO tt.sites (key, label, kind, status, scope) VALUES\n");
        sql.Append(rows).Append('\n');
        sql.Append("ON CONFLICT (key) DO UPDATE\n");
        sql.Append("  SET label = EXCLUDED.label, kind = EXCLUDED.kind, status = EXCLUDED.status, scope = EXCLUDED.scope\n");
        sql.Append("  WHERE (tt.sites.label, tt.sites.kind, tt.sites.status, tt.sites.scope)\n");
        sql.Append("        IS DISTINCT FROM (EXCLUDED.label, EXCLUDED.kind, EXCLUDED.status, EXCLUDED.scope);\n");
        sql.Append($"UPDATE tt.sites SET status = 'retired' WHERE key NOT IN ({keys}) AND status <> 'retired';\n");
        return sql.ToString();
    }

    private static string Q(string value) => "'" + value.Replace("'", "''", StringComparison.Ordinal) + "'";
}
